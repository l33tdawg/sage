type scopeGeneratedObservation struct {
	bytes   int64
	sets    map[string]bool
	deletes map[string]bool
}

// Observe actual journaled targets, then read their actual values. This does
// not reproduce a reservation estimate or multiply worst-case component sizes.
// These operations must not mutate one key twice within a single observation;
// otherwise a final-value scan would miss an intermediate Set's byte length.
func observeScopeGeneratedMutation(t *testing.T, s *BadgerStore, mutate func()) scopeGeneratedObservation {
	t.Helper()
	require.NotNil(t, s.appV30WriteStage)
	start := len(s.appV30WriteStage.journal)
	before := s.AppV30WriteStageStats().Generated
	mutate()
	seen := make(map[string]bool)
	got := scopeGeneratedObservation{sets: make(map[string]bool), deletes: make(map[string]bool)}
	for _, entry := range s.appV30WriteStage.journal[start:] {
		key := string(entry.key)
		require.False(t, seen[key], "a repeated target requires an intermediate-value observer")
		seen[key] = true
		item, err := s.txn.Get(entry.key)
		if errors.Is(err, badger.ErrKeyNotFound) {
			// The accepted generated-delete policy charges the actual key and
			// a 20-byte tombstone, independently of its previous value length.
			got.bytes += int64(len(entry.key)) + 20
			got.deletes[key] = true
			continue
		}
		require.NoError(t, err)
		value, err := item.ValueCopy(nil)
		require.NoError(t, err)
		got.bytes += int64(len(entry.key) + len(value))
		got.sets[key] = true
	}
	require.Equal(t, got.bytes, s.AppV30WriteStageStats().Generated-before,
		"all actual mutation targets, including scope/index and deletion tombstones, must be charged")
	return got
}

func scopeBoundMemoryID(i int) string {
	prefix := fmt.Sprintf("scope-write-bound-%04d-", i)
	return prefix + strings.Repeat("x", taint.MaxMemoryIDBytes-len(prefix))
}

func TestTaintScopeGeneratedBoundsActualJournalBytes(t *testing.T) {
	s := openTaintStore(t)
	chainID := strings.Repeat("c", tx.MaxDerivedFromChainIDBytes)
	target := tx.ParentRef{SourceChainID: chainID, MemoryID: strings.Repeat("t", taint.MaxMemoryIDBytes), ContentHash: sha256.Sum256([]byte("scope write target"))}
	require.NoError(t, s.SetMemoryHash(target.MemoryID, target.ContentHash[:], "committed"))
	// More than both the conservative204 expansion ceiling and the reachable
	// 340-member cleanup batch. Every child is a real canonical max-ID record.
	children := 2 * taint.MaxNewMembershipsPerExec
	for i := 0; i < children; i++ {
		id := scopeBoundMemoryID(i)
		hash := sha256.Sum256([]byte(id))
		require.NoError(t, s.SetMemoryHash(id, hash[:], "committed"))
		require.NoError(t, s.SetMemoryLineage(id, []tx.ParentRef{target}))
	}
	credentials := make([]string, tx.MaxTaintCredentialSetEntries)
	for i := range credentials {
		credentials[i] = fmt.Sprintf("%064x", i+1)
	}
	id := testTaintDecisionID("actual journal bound")
	payloadHash := sha256.Sum256([]byte("actual max credential scope"))
	scoped := s.BeginConsensusTransaction(nil)
	t.Cleanup(scoped.DiscardConsensusTransaction)
	begin := func() { require.NoError(t, scoped.BeginAppV30WriteStage(4<<20)) }
	end := func(observed int64) {
		stats, err := scoped.CommitAppV30WriteStage()
		require.NoError(t, err)
		require.Equal(t, observed, stats.Generated)
		t.Logf("actual staged generated bytes=%d", observed)
	}
	begin()
	applied := observeScopeGeneratedMutation(t, scoped, func() {
		created, err := scoped.ApplyTaintDecisionWithScope(chainID, id, target, payloadHash,
			TaintDecisionScope{Kind: tx.TaintScopeCredentialSet, Credentials: credentials})
		require.NoError(t, err)
		require.True(t, created)
	})
	for _, key := range [][]byte{taint.TargetKey(id), TaintDecisionScopeKey(id), taint.ActiveDecisionKey(id)} {
		require.True(t, applied.sets[string(key)], "immutable target, scope and retained-slot index are actual writes")
	}
	storedScope, found, err := scoped.GetTaintDecisionScope(id)
	require.NoError(t, err)
	require.True(t, found)
	require.Equal(t, credentials, storedScope.Credentials)
	end(applied.bytes)

	complete := false
	for call := 0; call < 12; call++ {
		begin()
		var expanded TaintExpandResult
		observed := observeScopeGeneratedMutation(t, scoped, func() {
			var err error
			expanded, err = scoped.ExpandTaintDecision(chainID, id, taint.PerExecutionUnitBudget)
			require.NoError(t, err)
		})
		require.LessOrEqual(t, expanded.Units, taint.PerExecutionUnitBudget)
		require.LessOrEqual(t, expanded.Materialized, taint.MaxNewMembershipsPerExec)
		if call == 0 {
			require.Greater(t, expanded.Materialized, taint.MaxNewMembershipsPerExec/2)
			header, found, err := scoped.GetTaintDecision(id)
			require.NoError(t, err)
			require.True(t, found)
			require.Len(t, header.ParentRefID, taint.DecisionIDBytes)
			require.Len(t, header.ParentMemoryID, taint.MaxMemoryIDBytes)
			require.Len(t, header.LastEdge, taint.MaxCursorBytes)
			encoded, err := taint.EncodeHeader(header)
			require.NoError(t, err)
			require.Greater(t, len(taint.DecisionKey(id))+len(encoded), 1172,
				"the old header component alone is not a full key/value bound")
			t.Logf("saturated expansion: materialized=%d units=%d actual-header-key-value=%d", expanded.Materialized, expanded.Units, len(taint.DecisionKey(id))+len(encoded))
		}
		end(observed.bytes)
		if expanded.Status == taint.StatusComplete {
			complete = true
			break
		}
	}
	require.True(t, complete)
	header, found, err := scoped.GetTaintDecision(id)
	require.NoError(t, err)
	require.True(t, found)
	require.EqualValues(t, children+1, header.Materialized)
	begin()
	cleared := observeScopeGeneratedMutation(t, scoped, func() {
		changed, err := scoped.ClearTaintDecision(id)
		require.NoError(t, err)
		require.True(t, changed)
	})
	require.False(t, cleared.deletes[string(taint.ActiveDecisionKey(id))], "Cleaning retains its slot")
	end(cleared.bytes)

	released, clean := 0, false
	for call := 0; call < 8; call++ {
		begin()
		var cleaned TaintCleanupResult
		observed := observeScopeGeneratedMutation(t, scoped, func() {
			var err error
			cleaned, err = scoped.CleanupTaintDecision(id, taint.PerExecutionUnitBudget)
			require.NoError(t, err)
		})
		if call == 0 {
			require.Equal(t, 340, cleaned.MembersDeleted, "the reviewed maximum member batch must actually execute")
		}
		if observed.deletes[string(taint.ActiveDecisionKey(id))] {
			released++
			require.True(t, cleaned.ActiveReleased)
			require.Equal(t, taint.StatusClean, cleaned.Status)
		}
		end(observed.bytes)
		if cleaned.Status == taint.StatusClean {
			clean = true
			break
		}
	}
	require.True(t, clean)
	require.Equal(t, 1, released, "the actual retained-index delete and its tombstone are charged once")
	count, err := scoped.ActiveTaintDecisionCount()
	require.NoError(t, err)
	require.Zero(t, count)
	require.NoError(t, scoped.ValidateTaintState())
}
