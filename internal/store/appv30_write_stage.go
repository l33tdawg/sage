package store

import (
	"bytes"
	"errors"
	"fmt"

	badger "github.com/dgraph-io/badger/v4"
)

const appV30TombstoneBytes int64 = 20

var ErrAppV30WriteReservationExceeded = errors.New(
	"app-v30 transaction exceeded its generated-write reservation",
)

type appV30MutationBeforeImage struct {
	value  []byte
	exists bool
}

type appV30JournalEntry struct {
	key    []byte
	before appV30MutationBeforeImage
}

type appV30StageSnapshot struct {
	domainOwnershipMutated           bool
	authorizationMutated             bool
	authorizationPeers               map[string]struct{}
	canonicalMemoryProjectionMutated bool
	graphAuthorizationMutated        bool
	publicMemoryChanged              map[string]struct{}
	poisoned                         error
}

type appV30WriteStage struct {
	limit         int64
	generatedUsed int64
	overflowed    bool
	journal       []appV30JournalEntry
	snapshot      appV30StageSnapshot
}

// AppV30WriteStageStats reports the generated bytes charged to the active
// stage. It is intended for consensus tests and telemetry, never for consensus
// decisions.
type AppV30WriteStageStats struct {
	Limit      int64
	Generated  int64
	Overflowed bool
}

// BeginAppV30WriteStage starts one rollback-safe transaction boundary. The
// limit is the deterministic generated-write estimate reserved for this tx.
func (s *BadgerStore) BeginAppV30WriteStage(limit int64) error {
	if s == nil || s.txn == nil {
		return errors.New("store: app-v30 write staging requires a consensus transaction")
	}
	if limit <= 0 {
		return errors.New("store: app-v30 write reservation must be positive")
	}
	if s.appV30WriteStage != nil {
		return errors.New("store: nested app-v30 write stage")
	}
	if s.poisoned != nil {
		return s.poisoned
	}
	s.appV30WriteStage = &appV30WriteStage{
		limit: limit,
		snapshot: appV30StageSnapshot{
			domainOwnershipMutated:           s.domainOwnershipMutated,
			authorizationMutated:             s.authorizationMutated,
			authorizationPeers:               cloneStringSet(s.authorizationPeers),
			canonicalMemoryProjectionMutated: s.canonicalMemoryProjectionMutated,
			graphAuthorizationMutated:        s.graphAuthorizationMutated,
			publicMemoryChanged:              cloneStringSet(s.publicMemoryChanged),
			poisoned:                         s.poisoned,
		},
	}
	return nil
}

func (s *BadgerStore) AppV30WriteStageStats() AppV30WriteStageStats {
	if s == nil || s.appV30WriteStage == nil {
		return AppV30WriteStageStats{}
	}
	return AppV30WriteStageStats{
		Limit:      s.appV30WriteStage.limit,
		Generated:  s.appV30WriteStage.generatedUsed,
		Overflowed: s.appV30WriteStage.overflowed,
	}
}

func (s *BadgerStore) AppV30WriteStageOverflowed() bool {
	return s != nil && s.appV30WriteStage != nil && s.appV30WriteStage.overflowed
}

// CommitAppV30WriteStage ends a successful transaction boundary. Every
// mutation remains in the enclosing consensus transaction.
func (s *BadgerStore) CommitAppV30WriteStage() (AppV30WriteStageStats, error) {
	if s == nil || s.appV30WriteStage == nil {
		return AppV30WriteStageStats{}, errors.New("store: no active app-v30 write stage")
	}
	stats := s.AppV30WriteStageStats()
	if stats.Overflowed {
		return stats, ErrAppV30WriteReservationExceeded
	}
	s.appV30WriteStage = nil
	return stats, nil
}

// AbortAppV30WriteStage rolls back this transaction's mutations in reverse
// order. The enclosing consensus transaction and its conflict/read set stay
// live, so later transactions in the same block retain normal Badger safety.
func (s *BadgerStore) AbortAppV30WriteStage() error {
	if s == nil || s.appV30WriteStage == nil {
		return nil
	}
	stage := s.appV30WriteStage
	var rollbackErr error
	for i := len(stage.journal) - 1; i >= 0; i-- {
		entry := stage.journal[i]
		var err error
		if entry.before.exists {
			err = s.txn.Set(entry.key, entry.before.value)
		} else {
			err = s.txn.Delete(entry.key)
		}
		if err != nil {
			rollbackErr = err
			break
		}
	}

	s.domainOwnershipMutated = stage.snapshot.domainOwnershipMutated
	s.authorizationMutated = stage.snapshot.authorizationMutated
	s.authorizationPeers = cloneStringSet(stage.snapshot.authorizationPeers)
	s.canonicalMemoryProjectionMutated = stage.snapshot.canonicalMemoryProjectionMutated
	s.graphAuthorizationMutated = stage.snapshot.graphAuthorizationMutated
	s.publicMemoryChanged = cloneStringSet(stage.snapshot.publicMemoryChanged)
	s.poisoned = stage.snapshot.poisoned
	s.updateMutated = false
	s.writeFailed = false
	s.appV30WriteStage = nil

	if rollbackErr != nil {
		s.poisoned = fmt.Errorf(
			"store: app-v30 transaction rollback failed after partial mutation: %w",
			rollbackErr,
		)
		return s.poisoned
	}
	return nil
}

func (s *BadgerStore) prepareAppV30StagedMutation(
	txn *badger.Txn,
	key []byte,
	setValue []byte,
	deleting bool,
) (*appV30MutationBeforeImage, error) {
	stage := s.appV30WriteStage
	if stage == nil {
		return nil, nil
	}
	if isAppV30GeneratedWriteKey(key) {
		cost := int64(len(key))
		if deleting {
			cost += appV30TombstoneBytes
		} else {
			cost += int64(len(setValue))
		}
		if cost > stage.limit-stage.generatedUsed {
			stage.overflowed = true
			return nil, ErrAppV30WriteReservationExceeded
		}
		stage.generatedUsed += cost
	}
	item, err := txn.Get(key)
	if errors.Is(err, badger.ErrKeyNotFound) {
		return &appV30MutationBeforeImage{}, nil
	}
	if err != nil {
		return nil, err
	}
	oldValue, err := item.ValueCopy(nil)
	if err != nil {
		return nil, err
	}
	return &appV30MutationBeforeImage{value: oldValue, exists: true}, nil
}

func (s *BadgerStore) recordAppV30StagedMutation(
	key []byte,
	before *appV30MutationBeforeImage,
) {
	stage := s.appV30WriteStage
	if stage == nil || before == nil {
		return
	}
	stage.journal = append(stage.journal, appV30JournalEntry{
		key:    append([]byte(nil), key...),
		before: *before,
	})
}

func isAppV30GeneratedWriteKey(key []byte) bool {
	for _, prefix := range [][]byte{
		[]byte("taintdec:"),
		[]byte("taintscope:"),
		[]byte("taintactivedec:"),
		[]byte("taintm:"),
		[]byte("taintd:"),
		[]byte("taintq:"),
		[]byte("taintrev"),
		[]byte("taintactive"),
		[]byte("memprov:v30:"),
		[]byte("lineage:"),
		[]byte("lineage-ref:"),
	} {
		if bytes.HasPrefix(key, prefix) {
			return true
		}
	}
	return false
}

func cloneStringSet(source map[string]struct{}) map[string]struct{} {
	if source == nil {
		return nil
	}
	cloned := make(map[string]struct{}, len(source))
	for key := range source {
		cloned[key] = struct{}{}
	}
	return cloned
}
